#!/usr/bin/env python3
"""Render U1's pad field to an image so the spatial question can be ANSWERED VISUALLY.

WHY A RENDER. pad_audit.py reports pad numbers, which is exact but STATIC: it says "13 pads share the
number 41 at 13 distinct positions". What it cannot say is whether those thirteen sit somewhere
electrically meaningful -- and that is a SPATIAL question, which is what the visual consultant is for.

THE QUESTION THIS ENABLES: U1 is the ESP32-S3 module. Its 12 small pads (all numbered 41, all on GND)
plus one 3.9 mm thermal pad sit in a cluster; nine FURTHER pads carry no number and no net. Are the nine
unnamed ones in the middle of that ground cluster (i.e. missing ground vias that should tie the module's
thermal pad to the plane), or are they elsewhere entirely (i.e. a different fault)? The pad NUMBERS
cannot answer that. A labelled render can.

This draws U1's own pad field, colour-coded by class, with the pad number printed on each pad, plus the
position of U4 (the SX1280 radio) for context.

Output: docs/fab/reviews/u1-pad-field.svg (+ .png)
Run:    ~/venvs/kicad/bin/python render_u1_pad_field.py
"""
import hashlib
import os
import shutil
import subprocess
import sys

import pcbnew

BOARD = "tracker/hardware/hub_board_v9.kicad_pcb"
OUT = "docs/fab/reviews/u1-pad-field.svg"
SCALE = 120.0   # svg units per mm


def main():
    b = pcbnew.LoadBoard(BOARD)
    u1 = b.FindFootprintByReference("U1")
    if u1 is None:
        print("U1 absent")
        return 1
    c = u1.GetPosition()
    cx, cy = pcbnew.ToMM(c.x), pcbnew.ToMM(c.y)

    # local frame: relative to U1's origin so the drawing is stable if the part moves
    def L(p):
        q = p.GetPosition()
        return (pcbnew.ToMM(q.x) - cx, pcbnew.ToMM(q.y) - cy)

    W, H = 1100, 1100
    ox, oy = W / 2, H / 2
    p = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}" '
         f'font-family="DejaVu Sans, Helvetica, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
         '<text x="30" y="34" font-size="21" font-weight="bold">'
         'U1 (ESP32-S3-WROOM-1U) pad field — why the audit flags it</text>',
         f'<text x="30" y="58" font-size="13" fill="#444">board sha256 '
         f'{hashlib.sha256(open(BOARD,"rb").read()).hexdigest()[:16]}… · U1 at ({cx:.2f},{cy:.2f}) mm · '
         f'coordinates shown relative to U1 · generated by render_u1_pad_field.py</text>',
         '<defs><marker id="a" markerWidth="9" markerHeight="9" refX="4.5" refY="4.5" orient="auto">'
         '<path d="M0,4.5 L9,2 L9,7 z" fill="#333"/></marker></defs>']

    # faint axes through U1's origin
    p.append(f'<line x1="0" y1="{oy}" x2="{W}" y2="{oy}" stroke="#eee" stroke-width="1"/>')
    p.append(f'<line x1="{ox}" y1="0" x2="{ox}" y2="{H}" stroke="#eee" stroke-width="1"/>')

    groups = {"41": [], "unnamed": [], "other": []}
    for pad in u1.Pads():
        n = str(pad.GetNumber())
        key = "unnamed" if n.strip() == "" else ("41" if n == "41" else "other")
        groups[key].append(pad)

    fills = {"41": "#c8751a", "unnamed": "#b00020", "other": "#7f8c9a"}
    strokes = {"41": "#8a4d0c", "unnamed": "#6d0014", "other": "#55606b"}

    for key in ("other", "41", "unnamed"):
        for pad in groups[key]:
            x, y = L(pad)
            s = pad.GetSize()
            w = max(pcbnew.ToMM(s.x) * SCALE, 6.0)
            h = max(pcbnew.ToMM(s.y) * SCALE, 6.0)
            sx, sy = ox + x * SCALE, oy + y * SCALE
            p.append(f'<rect x="{sx-w/2:.1f}" y="{sy-h/2:.1f}" width="{w:.1f}" height="{h:.1f}" '
                     f'fill="{fills[key]}" fill-opacity="0.85" stroke="{strokes[key]}" '
                     f'stroke-width="1.2" rx="1"/>')
            lbl = str(pad.GetNumber()) if key != "unnamed" else "—"
            if w >= 16 and h >= 12:
                p.append(f'<text x="{sx:.1f}" y="{sy+4:.1f}" font-size="10" fill="#fff" '
                         f'text-anchor="middle">{lbl}</text>')

    # the 3.9 mm thermal pad is huge at this scale; mark it explicitly
    for pad in groups["41"]:
        s = pad.GetSize()
        if pcbnew.ToMM(s.x) > 2.0:
            x, y = L(pad)
            sx, sy = ox + x * SCALE, oy + y * SCALE
            p.append(f'<text x="{sx:.1f}" y="{sy+4:.1f}" font-size="15" font-weight="bold" '
                     f'fill="#fff" text-anchor="middle">41</text>')
            p.append(f'<text x="{sx:.1f}" y="{sy-pcbnew.ToMM(s.y)*SCALE/2-10:.1f}" font-size="12" '
                     f'fill="#8a4d0c" text-anchor="middle">thermal pad, 3.9 mm</text>')

    # U4's position for context
    u4 = b.FindFootprintByReference("U4")
    if u4 is not None:
        q = u4.GetPosition()
        ux, uy = pcbnew.ToMM(q.x) - cx, pcbnew.ToMM(q.y) - cy
        sx, sy = ox + ux * SCALE, oy + uy * SCALE
        if 0 < sx < W and 0 < sy < H:
            p.append(f'<circle cx="{sx:.1f}" cy="{sy:.1f}" r="7" fill="none" stroke="#2f6fb0" '
                     f'stroke-width="2.5"/>')
            p.append(f'<text x="{sx+12:.1f}" y="{sy+5:.1f}" font-size="13" fill="#2f6fb0">'
                     f'U4 (SX1280 radio)</text>')

    # legend
    ly = H - 120
    rows = [("#c8751a", f"numbered 41 — {len(groups['41'])} pads, ALL net=GND, two sizes"),
            ("#b00020", f"UNNAMED — {len(groups['unnamed'])} pads, ALL net=(none): floating copper"),
            ("#7f8c9a", f"other numbered pads — {len(groups['other'])}")]
    p.append(f'<text x="30" y="{ly-14}" font-size="15" font-weight="bold">legend</text>')
    for i, (col, txt) in enumerate(rows):
        yy = ly + i * 24
        p.append(f'<rect x="30" y="{yy-11}" width="16" height="14" fill="{col}" '
                 f'stroke="#333" stroke-width="0.7"/>')
        p.append(f'<text x="54" y="{yy}" font-size="13">{txt}</text>')
    p.append(f'<text x="30" y="{H-20}" font-size="12.5" fill="#333">'
             'THE QUESTION FOR A VISUAL REVIEW: are the unnamed pads inside the ground cluster (missing '
             'vias) or separate from it (a different fault)?</text>')
    p.append('</svg>')

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    svg = "\n".join(p)
    with open(OUT, "w") as fh:
        fh.write(svg)
    print(f"wrote {OUT}")
    png = OUT.replace(".svg", ".png")
    if shutil.which("rsvg-convert"):
        r = subprocess.run(["rsvg-convert", "-w", "1500", OUT, "-o", png],
                           capture_output=True, text=True)
        if not os.path.exists(png):
            print(f"RENDER FAILED: {(r.stderr or r.stdout or '')[:300]}")
            return 1
        print(f"wrote {png} ({os.path.getsize(png)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
