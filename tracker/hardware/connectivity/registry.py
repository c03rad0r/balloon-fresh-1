#!/usr/bin/env python3
"""The v10 connectivity registry -- ONE version-controlled source of truth for pin->net.

Why this exists (operator, 2026-10-21): "where do you track which pins need to be
connected where? Do you have a single registry of such decisions somewhere?"

Before this file the answer was NO: pin->net truth was scattered across five places --
the v9 netlist, make_v10_netlist.py's rename tables, hand-typed special cases inside
build_hub_board_v10.py, ADRs written in prose, and footprint sidecar .md files. Nothing
could detect when those five disagreed, and a wrong pin (U_C.9) survived every check.

FORMAT -- one line per pin, diff-friendly, human-auditable, no dependencies:

    REF.PIN   NET             # authority

  * every pin of every component appears exactly once, sorted (ref, numeric pin)
  * NET is the net name, or UNASSIGNED for a pin with no net
  * the comment carries the AUTHORITY: which ADR or measurement decided it
  * the file is the REGISTRY. The netlist and the board are generated/checked against it.

Usage:
    registry.py gen    --board B --out R   # write/refresh the registry from a board
    registry.py check  --board B --reg R   # assert board == registry (exit 1 on drift)
"""
import argparse
import os
import re
import sys

import pcbnew

UM = 1_000_000.0
HOLE_PREFIXES = ("H", "HW")
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_BOARD = os.path.join(HERE, "..", "hub_board_v10.kicad_pcb")
DEFAULT_REG = os.path.join(HERE, "v10_pinmap.reg")


def pin_sort_key(num):
    return (0, int(num)) if num.isdigit() else (1, num)


def read_board(path):
    b = pcbnew.LoadBoard(path)
    if b is None:
        raise SystemExit(f"REFUSED: cannot load {path}")
    out = {}
    for fp in b.GetFootprints():
        ref = fp.GetReference()
        if ref.startswith(HOLE_PREFIXES):
            continue
        pins = {}
        for p in fp.Pads():
            n = p.GetNet()
            num = p.GetNumber() or '""'
            pins[num] = n.GetNetname() if n and n.GetNetCode() else "UNASSIGNED"
        out[ref] = (fp.GetFPID().GetLibItemName(), pins)
    return out


def load_registry(path):
    """Parse the registry file -> {ref: {pin: net}} plus the authority comments."""
    reg, comments = {}, {}
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            m = re.match(r"^([A-Za-z0-9_]+)\.(\S*)\s+(\S+)$", line)
            if not m:
                raise SystemExit(f"REFUSED: unparseable registry line: {raw.rstrip()}")
            ref, pin, net = m.group(1), m.group(2), m.group(3)
            if pin == "":
                pin = '""'   # shield pads have an empty pad number in KiCad
            reg.setdefault(ref, {})[pin] = net
            comments[(ref, pin)] = raw.split("#", 1)[1].strip() if "#" in raw else ""
    return reg, comments


# Authority table: which decision fixed each net family. Keeps provenance IN the registry
# so a reader can go from a pin to the ADR that decided it.
AUTHORITY = [
    (r"^/SPI1_", "ADR-123 (2.4GHz bus: U3+U_C+E28)"),
    (r"^/SPI2_", "ADR-123 (433MHz bus: F33 alone)"),
    (r"^/ANT_C_2G4$", "ADR-119 (Site C antenna, split from U3 feed)"),
    (r"^/ANT3_2G4_RX$", "ADR-119 (Site B antenna)"),
    (r"^/ANT1_433_TX$", "ADR-119 (Site A antenna)"),
    (r"^/ANT2_2G4_RANGE$", "ADR-119 (Site D antenna)"),
    (r"^/ANT4_GNSS_L1$", "ADR-119 (GNSS antenna)"),
    (r"^/(EN|USB_DN|USB_DP|IO0)$", "ADR-121 (J_PROG)"),
    (r"^/E28_", "ADR-118 + E28 sidecar pin map"),
    (r"^/U_C_", "ADR-119 Site C control (copied by pad number)"),
    (r"^/U3_", "v9 netlist + ADR-123"),
    (r"^/F33_", "v9 netlist (F33 control)"),
    (r"^/GNSS_", "v9 netlist (MAX-M10S)"),
    (r"^/I2C_", "v9 netlist (baro U6)"),
    (r"^/CUT_SENSE_|^/W[0-9]_SOLAR", "v9 netlist (wing cut/solar)"),
    (r"^/SCAP_MID$|^/VSCAP$", "v9 netlist (harvest storage)"),
    (r"^GND$|^\+3V3$", "v9 netlist (rails)"),
]


def authority_for(net):
    for pat, src in AUTHORITY:
        if re.search(pat, net):
            return src
    return "v9 netlist (unclassified)"


def cmd_gen(args):
    board = read_board(args.board)
    lines = [
        "# v10 flight-board connectivity registry -- SOURCE OF TRUTH for pin->net.",
        "# Generated by registry.py gen; every change is a deliberate commit.",
        "# Format: REF.PIN  NET  # authority",
        "# UNASSIGNED = the pin has no net. Those are listed at the end of this file.",
        "",
    ]
    unassigned = []
    for ref in sorted(board, key=lambda r: (len(r), r)):
        part, pins = board[ref]
        lines.append(f"# --- {ref}  ({part})")
        for pin in sorted(pins, key=pin_sort_key):
            net = pins[pin]
            auth = ("SEE connectivity/OPEN-ITEMS.md" if net == "UNASSIGNED"
                    else authority_for(net))
            lines.append(f"{ref}.{pin}  {net}  # {auth}")
            if net == "UNASSIGNED":
                unassigned.append(f"{ref}.{pin}")
        lines.append("")
    lines.append(f"# UNASSIGNED pins on this board: {len(unassigned)} -> {', '.join(unassigned)}")
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}: {sum(len(v[1]) for v in board.values())} pins, "
          f"{len(unassigned)} unassigned")
    return 0


def cmd_check(args):
    board = read_board(args.board)
    reg, comments = load_registry(args.reg)
    drift, missing = [], []
    for ref, (part, pins) in board.items():
        for pin, net in pins.items():
            want = reg.get(ref, {}).get(pin)
            if want is None:
                missing.append(f"{ref}.{pin} is on the board as {net} but absent from the registry")
            elif want != net:
                drift.append(f"{ref}.{pin}: board={net}  registry={want}")
    for ref, pins in reg.items():
        for pin in pins:
            if ref not in board:
                missing.append(f"{ref}.{pin} is in the registry but {ref} is not on the board")
            elif pin not in board[ref][1]:
                missing.append(f"{ref}.{pin} is in the registry but not on the board")
    unassigned = [f"{r}.{p}" for r, (_part, pins) in board.items()
                  for p, n in pins.items() if n == "UNASSIGNED"]
    for v in drift + missing:
        print("  DRIFT:", v)
    print(f"pins checked: {sum(len(v[1]) for v in board.values())}")
    print(f"UNASSIGNED pins: {len(unassigned)} -> {', '.join(sorted(unassigned))}")
    print(f"DRIFT: {len(drift)}   MISSING: {len(missing)}")
    return 1 if (drift or missing) else 0


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen")
    g.add_argument("--board", default=DEFAULT_BOARD)
    g.add_argument("--out", default=DEFAULT_REG)
    g.set_defaults(func=cmd_gen)
    c = sub.add_parser("check")
    c.add_argument("--board", default=DEFAULT_BOARD)
    c.add_argument("--reg", default=DEFAULT_REG)
    c.set_defaults(func=cmd_check)
    args = ap.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())