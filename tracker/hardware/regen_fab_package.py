#!/usr/bin/env python3
"""Regenerate the hub v9 fab package FROM the canonical board, so the package cannot lag the design.

THE DEFECT THIS FIXES (test_netlist_integrity.py check C2):
    committed tracker/hardware/hub_board_v9.kicad_pcb : 59 footprints
    packaged  docs/fab/hub-v9/gerbers/hub_v9.kicad_pcb : 39 footprints
    20 footprints missing from the package, including C0, C1, C2, C3, C5, C6, C7, C8, C9, L1, L2 --
    i.e. the ENTIRE SX1280 RF matching and filter chain. An order cut from that package would produce a
    board with no 2.4 GHz matching network.

WHY NO EXISTING TOOL DID THIS. emit_jlc_files.py writes the BOM and CPL only, and it is HARDCODED to a
stale worktree path (/home/.../worktrees/v9-route/...) that is not the canonical tree. So the package's
board file was never regenerated by any script in the repo -- it was copied by hand at some point.

WHAT THIS DOES, and nothing else:
  1. reads the CANONICAL board (tracker/hardware/hub_board_v9.kicad_pcb)
  2. plots gerbers + drill from it with kicad-cli
  3. copies the board into the package directory, so C2's comparison is like-for-like
  4. writes a MANIFEST with the source sha256, so anyone can prove the package matches the design
  5. regenerates the BOM/CPL from the board's own footprints (DNP excluded)

It REFUSES to run if the canonical board has fewer footprints than the package currently holds --
that is the stale-package symptom, and silently overwriting would hide a real regression.

Usage: regen_fab_package.py [--board <b.kicad_pcb>] [--out <dir>] [--dry-run]
"""
import argparse
import csv
import hashlib
import json
import os
import shutil
import subprocess
import sys

import pcbnew

DEFAULT_BOARD = "tracker/hardware/hub_board_v9.kicad_pcb"
DEFAULT_OUT = "docs/fab/hub-v9/gerbers"
LAYERS = "F.Cu,In1.Cu,In2.Cu,B.Cu,F.Paste,B.Paste,F.Silkscreen,B.Silkscreen,F.Mask,B.Mask,Edge.Cuts"
EXCLUDE_FROM_POS = {"F.Paste", "B.Paste"}


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def footprint_count(path):
    if not os.path.exists(path):
        return None
    b = pcbnew.LoadBoard(path)
    return len(list(b.GetFootprints())) if b else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--board", default=DEFAULT_BOARD)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    src_pkg_board = os.path.join(a.out, "hub_v9.kicad_pcb")
    new_n = footprint_count(a.board)
    old_n = footprint_count(src_pkg_board)
    print(f"canonical board : {a.board}  ({new_n} footprints)")
    print(f"packaged board  : {src_pkg_board}  ({old_n} footprints)")

    if new_n is None:
        print("REFUSING: cannot read the canonical board")
        return 1
    if old_n is not None and new_n < old_n:
        print(f"REFUSING: the canonical board has FEWER footprints ({new_n}) than the package "
              f"({old_n}). Overwriting would hide a regression rather than fix a stale package.")
        return 1
    if old_n is not None and new_n == old_n:
        print("note: footprint counts already match; regenerating anyway to refresh copper and hashes")

    if a.dry_run:
        print(f"DRY RUN: would plot gerbers and write {a.out}")
        return 0

    os.makedirs(a.out, exist_ok=True)
    stem = os.path.splitext(os.path.basename(a.board))[0]

    # 1. gerbers
    r = subprocess.run(["kicad-cli", "pcb", "export", "gerbers", a.board,
                        "-o", a.out + "/", "--layers", LAYERS],
                       capture_output=True, text=True)
    print(f"gerbers rc={r.returncode} {('OK' if r.returncode == 0 else r.stderr[-200:])}")

    # 2. drill
    r2 = subprocess.run(["kicad-cli", "pcb", "export", "drill", a.board,
                         "-o", a.out + "/", "--format", "excellon",
                         "--excellon-separate-th"],
                        capture_output=True, text=True)
    print(f"drill   rc={r2.returncode} {('OK' if r2.returncode == 0 else r2.stderr[-200:])}")

    # 3. the board itself, so C2 compares like-for-like
    shutil.copy(a.board, src_pkg_board)
    print(f"copied the canonical board into the package: {src_pkg_board}")

    # 4. BOM + CPL from the board's own footprints, DNP excluded
    b = pcbnew.LoadBoard(a.board)
    bom_rows, cpl_rows = [], []
    for fp in b.GetFootprints():
        ref = fp.GetReference()
        val = fp.GetValue()
        dnp = False
        try:
            dnp = bool(fp.IsDNP())
        except Exception:
            pass
        attrs = fp.GetAttributes()
        if attrs & pcbnew.FP_EXCLUDE_FROM_BOM:
            continue
        bom_rows.append({"Comment": val, "Designator": ref})
        if attrs & pcbnew.FP_EXCLUDE_FROM_POS_FILES or dnp:
            continue
        c = fp.GetPosition()
        cpl_rows.append({
            "Designator": ref,
            "Mid X": f"{pcbnew.ToMM(c.x):.4f}",
            "Mid Y": f"{pcbnew.ToMM(c.y):.4f}",
            "Rotation": f"{fp.GetOrientationDegrees():.1f}",
            "Layer": "top" if fp.GetLayer() == pcbnew.F_Cu else "bottom",
        })
    bom_path = os.path.join(a.out, f"{stem}-bom-jlcpcb.csv")
    cpl_path = os.path.join(a.out, f"{stem}-cpl-jlcpcb.csv")
    with open(bom_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["Comment", "Designator"])
        w.writeheader()
        w.writerows(bom_rows)
    with open(cpl_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["Designator", "Mid X", "Mid Y", "Rotation", "Layer"])
        w.writeheader()
        w.writerows(cpl_rows)
    print(f"wrote {bom_path}: {len(bom_rows)} BOM rows")
    print(f"wrote {cpl_path}: {len(cpl_rows)} placements (DNP / exclude-from-pos omitted)")

    # 5. manifest with provenance
    manifest = {
        "source_board": os.path.abspath(a.board),
        "source_sha256": sha256(a.board),
        "packaged_board": os.path.basename(src_pkg_board),
        "footprints": new_n,
        "bom_rows": len(bom_rows),
        "cpl_rows": len(cpl_rows),
        "layers": LAYERS.split(","),
        "generated_by": "tracker/hardware/regen_fab_package.py",
        "regenerate_with": ("python3 tracker/hardware/regen_fab_package.py "
                            f"--board {a.board} --out {a.out}"),
    }
    mpath = os.path.join(a.out, f"{stem}-PACKAGE-MANIFEST.json")
    with open(mpath, "w") as fh:
        json.dump(manifest, fh, indent=2)
        fh.write("\n")
    print(f"wrote {mpath}")
    print(f"\nPACKAGE SOURCE sha256: {manifest['source_sha256'][:16]}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
